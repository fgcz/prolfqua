# Correctness against previous implementations and standard datasets with known properties.

#' @srrstats {G5.0} Standard datasets with known properties: datasets::PlantGrowth and datasets::ToothGrowth
#'   (compared with stats::lm) and the packaged IonStar spike-in subset, whose E. coli proteins change by the
#'   known dilution ratios while human proteins stay constant.
#' @srrstats {G5.4b} prolfqua re-implements existing methods; tests compare them with the original software:
#'   lm contrasts with stats::lm, limma with lmFit/contrasts.fit/eBayes, lmer_nested with lmerTest::contest,
#'   rlm with MASS::rlm, rfit with Rfit::rfit, and deqms with stored DEqMS::spectraCounteBayes() output
#'   (inst/extdata/deqms_reference.rds, generated by data-raw/make_deqms_reference.R).
#' @noRd
NULL

# One subject (protein) built from a plain data frame, so reference fits use the same rows.
one_subject_lfq <- function(data, factors, response, factor_depth = 1) {
  data$proteinID <- "P1"
  data$idtype2 <- "ref"
  data$sample <- sprintf("s%02d", seq_len(nrow(data)))
  data$abundance <- data[[response]]
  data$nr_children <- 1
  setup <- .sim_setup(data, factors, peptide = FALSE, factor_depth = factor_depth)
  setup$config$is_response_transformed <- TRUE
  LFQData$new(setup$data, setup$config)
}

lm_contrasts <- function(lfq, modelstr, contrasts) {
  Contrasts$new(build_model(lfq, strategy_lm(modelstr)), contrasts)$get_contrasts()
}

# Wald t test of the linear function L of an lm fit
wald_reference <- function(fit, L) {
  estimate <- sum(L * stats::coef(fit))
  se <- sqrt(as.numeric(t(L) %*% stats::vcov(fit) %*% L))
  df <- stats::df.residual(fit)
  c(estimate = estimate, std.error = se, df = df, p.value = 2 * stats::pt(-abs(estimate / se), df))
}

expect_contrast_equal <- function(row, reference, tolerance = 1e-8) {
  expect_equal(row$diff, unname(reference["estimate"]), tolerance = tolerance)
  expect_equal(row$std.error, unname(reference["std.error"]), tolerance = tolerance)
  expect_equal(row$df, unname(reference["df"]), tolerance = tolerance)
  expect_equal(row$p.value, unname(reference["p.value"]), tolerance = tolerance)
}

test_that("one-factor lm contrasts equal stats::lm on PlantGrowth", {
  lfq <- one_subject_lfq(datasets::PlantGrowth, list(group_ = "group"), "weight")
  res <- lm_contrasts(lfq, "abundance ~ group_", c(trt1_vs_ctrl = "group_trt1 - group_ctrl"))
  fit <- stats::lm(weight ~ group, data = datasets::PlantGrowth)
  expect_contrast_equal(res, wald_reference(fit, c(0, 1, 0)))
})

test_that("two-factor lm marginal and cell contrasts equal stats::lm on ToothGrowth", {
  tooth <- transform(datasets::ToothGrowth, dose = as.character(dose))
  lfq <- one_subject_lfq(tooth, list(supp_ = "supp", dose_ = "dose"), "len", factor_depth = 2)
  res <- lm_contrasts(
    lfq,
    "abundance ~ supp_ * dose_",
    c(VC_vs_OJ = "supp_VC - supp_OJ", VC_vs_OJ_dose2 = "`supp_VC:dose_2` - `supp_OJ:dose_2`")
  )
  fit <- stats::lm(len ~ supp * dose, data = tooth)
  grid <- expand.grid(supp = c("OJ", "VC"), dose = c("0.5", "1", "2"), stringsAsFactors = FALSE)
  X <- stats::model.matrix(~ supp * dose, grid)
  marginal <- colMeans(X[grid$supp == "VC", ]) - colMeans(X[grid$supp == "OJ", ])
  cell <- X[grid$supp == "VC" & grid$dose == "2", ] - X[grid$supp == "OJ" & grid$dose == "2", ]
  expect_contrast_equal(res[res$contrast == "VC_vs_OJ", ], wald_reference(fit, marginal))
  expect_contrast_equal(res[res$contrast == "VC_vs_OJ_dose2", ], wald_reference(fit, cell))
})

test_that("limma contrasts equal lmFit, contrasts.fit and eBayes", {
  sim <- sim_with_truth(Nprot = 60, seed = 11)
  res <- build_contrast_analysis(sim$lfqdata, "~ group_", RECOVERY_CONTRASTS, "limma")$get_contrasts()
  long <- sim$lfqdata$data_long()
  wide <- tidyr::pivot_wider(long, id_cols = "protein_Id", names_from = "sampleName", values_from = "abundance")
  expression <- as.matrix(wide[, -1])
  rownames(expression) <- wide$protein_Id
  annotation <- unique(long[, c("sampleName", "group_")])
  group <- factor(annotation$group_[match(colnames(expression), annotation$sampleName)])
  design <- stats::model.matrix(~ 0 + group)
  colnames(design) <- levels(group)
  contrast_matrix <- limma::makeContrasts(A_vs_Ctrl = A - Ctrl, B_vs_Ctrl = B - Ctrl, levels = design)
  fit <- limma::eBayes(limma::contrasts.fit(limma::lmFit(expression, design), contrast_matrix))
  for (contrast in colnames(contrast_matrix)) {
    reference <- limma::topTable(fit, coef = contrast, number = Inf, sort.by = "none")
    got <- res[res$contrast == contrast, ]
    got <- got[match(rownames(reference), got$protein_Id), ]
    expect_equal(got$diff, reference$logFC, tolerance = 1e-8)
    expect_equal(got$statistic, reference$t, tolerance = 1e-8)
    expect_equal(got$p.value, reference$P.Value, tolerance = 1e-8)
    expect_equal(got$df, unname(fit$df.total[match(rownames(reference), rownames(fit))]), tolerance = 1e-8)
  }
})

test_that("lmer contrasts equal lmerTest::contest on a directly fitted model", {
  skip_if_not_installed("lme4")
  skip_if_not_installed("lmerTest")
  sim <- sim_with_truth(Nprot = 20, seed = 5, peptide = TRUE)
  long <- sim$lfqdata$data_long()
  counts <- table(unique(long[, c("protein_Id", "peptide_Id")])$protein_Id)
  protein <- names(counts)[which.max(counts)]
  one <- long[long$protein_Id == protein, ]
  lfq <- LFQData$new(one, sim$lfqdata$get_config())
  modelstr <- "abundance ~ group_ + (1 | peptide_Id) + (1 | sampleName)"
  res <- Contrasts$new(build_model(lfq, strategy_lmer(modelstr)), c(A_vs_Ctrl = "group_A - group_Ctrl"))$get_contrasts()
  fit <- lmerTest::lmer(stats::as.formula(modelstr), data = one)
  L <- matrix(-(names(lme4::fixef(fit)) == "group_Ctrl"), nrow = 1)
  reference <- lmerTest::contest(fit, L, joint = FALSE)
  expect_equal(res$diff, reference$Estimate, tolerance = 1e-6)
  expect_equal(res$std.error, reference$`Std. Error`, tolerance = 1e-6)
  expect_equal(res$df, reference$df, tolerance = 1e-6)
  expect_equal(res$p.value, reference$`Pr(>|t|)`, tolerance = 1e-6)
})

test_that("rlm and rfit coefficients equal MASS::rlm and Rfit::rfit", {
  sim <- sim_with_truth(Nprot = 10, seed = 3)
  rlm_model <- muffle_warnings_matching(
    build_model(sim$lfqdata, strategy_rlm("abundance ~ group_")),
    rlm_convergence_warning
  )
  coefficients <- rlm_model$get_coefficients()
  for (i in seq_len(nrow(rlm_model$model_df))) {
    row <- rlm_model$model_df[i, ]
    fit <- muffle_warnings_matching(
      MASS::rlm(abundance ~ group_, data = row$data[[1]], method = "M"),
      rlm_convergence_warning
    )
    got <- coefficients[coefficients$protein_Id == row$protein_Id, ]
    expect_equal(got$Estimate, unname(stats::coef(fit)), tolerance = 1e-8)
    expect_equal(got$Std..Error, unname(summary(fit)$coefficients[, "Std. Error"]), tolerance = 1e-8)
  }
  skip_if_not_installed("Rfit")
  rfit_model <- build_model(sim$lfqdata, strategy_rfit("abundance ~ group_"))
  rfit_coefficients <- rfit_model$get_coefficients()
  for (i in seq_len(nrow(rfit_model$model_df))) {
    row <- rfit_model$model_df[i, ]
    fit <- Rfit::rfit(abundance ~ group_, data = row$data[[1]])
    got <- rfit_coefficients[rfit_coefficients$protein_Id == row$protein_Id, ]
    expect_equal(got$Estimate, unname(stats::coef(fit)), tolerance = 1e-8)
  }
})

test_that("deqms equals stored DEqMS::spectraCounteBayes output", {
  stored <- readRDS(system.file("extdata", "deqms_reference.rds", package = "prolfqua"))
  setup <- .sim_setup(stored$raw, list(group_ = "group"), peptide = FALSE, nr_children = "nrPeptides")
  setup$config$is_response_transformed <- TRUE
  lfq <- LFQData$new(setup$data, setup$config)
  res <- build_contrast_analysis(lfq, "~ group_", RECOVERY_CONTRASTS, "deqms", weights = NULL)$get_contrasts()
  joined <- merge(res, stored$reference, by = c("protein_Id", "contrast"))
  expect_equal(nrow(joined), nrow(stored$reference))
  expect_equal(joined$diff, joined$logFC, tolerance = 1e-10)
  # DEqMS searches the prior df on a 0.1 grid; prolfqua solves for it exactly.
  expect_true(all(abs(joined$df - joined$sca.df) <= 0.1))
  expect_lt(max(abs(joined$statistic - joined$sca.t) / abs(joined$sca.t)), 1e-3)
  expect_lt(max(abs(joined$p.value - joined$sca.p)), 1e-3)
})

test_that("IonStar spike-in fold changes are recovered by lm and limma", {
  ionstar <- prolfqua_data("data_ionstar")$filtered()
  config <- ionstar$config$clone(deep = TRUE)
  config$factor_depth <- 1
  # The packaged peptide data carry no child counts; one peptide counts once.
  ionstar$data[[config$nr_children]] <- 1
  peptides <- LFQData$new(ionstar$data, config)$get_Transformer()$log2()$robscale()$lfq
  proteins <- muffle_warnings_matching(peptides$get_Aggregator()$aggregate(), "medpolish")
  contrasts <- c(
    b_vs_a = "dilution.b - dilution.a",
    c_vs_b = "dilution.c - dilution.b",
    d_vs_c = "dilution.d - dilution.c",
    e_vs_d = "dilution.e - dilution.d"
  )
  expected <- log2(c(b_vs_a = 4.5 / 3, c_vs_b = 6 / 4.5, d_vs_c = 7.5 / 6, e_vs_d = 9 / 7.5))
  for (method in c("lm", "limma")) {
    # A few proteins miss a whole dilution level; limma reports their partial coefficients.
    res <- muffle_warnings_matching(
      build_contrast_analysis(proteins, "~ dilution.", contrasts, method)$get_contrasts(),
      partial_na_warning
    )
    for (contrast in names(contrasts)) {
      rows <- res[res$contrast == contrast, ]
      ecoli <- stats::median(rows$diff[grepl("ECOLI", rows$protein_Id)])
      human <- stats::median(rows$diff[grepl("HUMAN", rows$protein_Id)])
      # Mass spectrometry compresses ratios, so E. coli estimates sit slightly below the dilution ratio.
      expect_lt(abs(ecoli - expected[[contrast]]), 0.15)
      expect_lt(abs(human), 0.1)
    }
  }
})
